-- Independent action ledger and durable queue; does not overwrite inspection facts.
CREATE TABLE iqc_action_execution (
 id VARCHAR(64) NOT NULL,
 idempotency_key CHAR(64) NOT NULL,
 task_id VARCHAR(64) NOT NULL,
 execution_id VARCHAR(64) NOT NULL,
 conversation_id VARCHAR(64) NOT NULL,
 source_result_id VARCHAR(64) NOT NULL,
 decision_reference VARCHAR(128) NOT NULL,
 action_policy_hash CHAR(64) NOT NULL,
 action_id VARCHAR(128) NOT NULL,
 action_type VARCHAR(64) NOT NULL,
 owner VARCHAR(128) NOT NULL,
 owner_group_id VARCHAR(64) NULL,
 input_snapshot_json LONGTEXT NOT NULL,
 input_snapshot_hash CHAR(64) NOT NULL,
 policy_snapshot_json LONGTEXT NOT NULL,
 status VARCHAR(40) NOT NULL,
 attempt_count INT NOT NULL DEFAULT 0,
 version BIGINT NOT NULL DEFAULT 0,
 next_attempt_at_utc DATETIME(3) NULL,
 claim_token CHAR(32) NULL,
 claimed_at_utc DATETIME(3) NULL,
 settled_at_utc DATETIME(3) NULL,
 outcome VARCHAR(40) NULL,
 evidence_reference VARCHAR(128) NULL,
 result_reference VARCHAR(128) NULL,
 last_error_code VARCHAR(64) NULL,
 created_by VARCHAR(128) NULL,
 created_time DATETIME(3) NULL,
 updated_by VARCHAR(128) NULL,
 updated_time DATETIME(3) NULL,
 PRIMARY KEY(id),
 UNIQUE KEY uk_iqc_action_idempotency(idempotency_key),
 KEY idx_iqc_action_dispatch(status,next_attempt_at_utc,id),
 KEY idx_iqc_action_execution(task_id,execution_id),
 KEY idx_iqc_action_result(source_result_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
