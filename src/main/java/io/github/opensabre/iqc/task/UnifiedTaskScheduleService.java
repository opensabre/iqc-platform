package io.github.opensabre.iqc.task;

import com.baomidou.mybatisplus.core.toolkit.Wrappers;
import com.fasterxml.jackson.databind.ObjectMapper;
import io.github.opensabre.iqc.governance.IqcException;
import io.github.opensabre.iqc.result.InspectionExecutionService;
import io.github.opensabre.iqc.shared.IqcDataScope;
import io.github.opensabre.iqc.task.dao.InspectionTaskMapper;
import io.github.opensabre.iqc.task.model.InspectionTask;
import java.time.LocalDateTime;
import java.util.List;
import lombok.RequiredArgsConstructor;
import org.springframework.scheduling.support.CronExpression;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

/** Trigger configuration over the existing task definition, queue and scheduler poller. */
@Service
@RequiredArgsConstructor
public class UnifiedTaskScheduleService {
    private final TaskWizardService wizard;
    private final InspectionTaskService tasks;
    private final InspectionTaskMapper mapper;
    private final InspectionExecutionService executions;
    private final IqcDataScope scope;
    private final ObjectMapper json;
    /** All unified trigger timestamps and Cron expressions use the same explicit zone. */
    public static LocalDateTime schedulingNow() { return LocalDateTime.now(java.time.ZoneId.of("Asia/Shanghai")); }
    public enum TriggerType { IMMEDIATE, SCHEDULED, PERIODIC }
    public record Trigger(TriggerType type, LocalDateTime scheduledAt, String cron, Boolean enabled) {
        public Trigger {
            if (type == null) throw IqcException.invalidArgument("请选择触发方式");
            if (type == TriggerType.SCHEDULED && (scheduledAt == null || cron != null))
                throw IqcException.invalidArgument("定时任务须指定执行时间，不允许 Cron");
            if (type == TriggerType.PERIODIC) {
                if (scheduledAt != null || cron == null || cron.isBlank()) throw IqcException.invalidArgument("周期任务须指定 Cron");
                try { CronExpression.parse(cron); }
                catch (IllegalArgumentException invalid) { throw IqcException.invalidArgument("Cron 表达式无效"); }
            }
            if (type == TriggerType.IMMEDIATE && (scheduledAt != null || cron != null))
                throw IqcException.invalidArgument("立即任务不能配置执行时间或 Cron");
            enabled = enabled == null ? true : enabled;
        }
        LocalDateTime next(LocalDateTime now) {
            var next = type == TriggerType.PERIODIC ? CronExpression.parse(cron).next(now)
                    : type == TriggerType.SCHEDULED ? scheduledAt : now;
            if (next == null) throw IqcException.invalidArgument("Cron 没有后续触发时间");
            return next;
        }
    }
    /** Authorization is generated by the server, separate from public Trigger fields. */
    private record StoredTrigger(Trigger trigger, IqcDataScope.ExecutionScope scope) { }

    /** Immediate execution is queued in this transaction; external engine calls start only after commit. */
    @Transactional(isolation = org.springframework.transaction.annotation.Isolation.REPEATABLE_READ)
    public InspectionTask create(String name, TaskDataSelection selection, UnifiedLabelPlanService.Configuration configuration,
                                 Integer concurrency, Trigger trigger) {
        LocalDateTime now = schedulingNow();
        var next = trigger.next(now);
        if (trigger.type() == TriggerType.SCHEDULED && !next.isAfter(now)) throw IqcException.invalidArgument("执行时间须晚于当前时间");
        var task = wizard.createUnified(name, selection, configuration, concurrency);
        task.setTriggerConfigurationJson(encode(new StoredTrigger(trigger, scope.captureExecutionScope())));
        task.setEnabled(trigger.enabled()); task.setScheduledTime(next);
        task.setStatus(trigger.enabled() ? "SCHEDULED" : "CREATED");
        if (trigger.type() == TriggerType.IMMEDIATE && trigger.enabled()) task.setStatus("CREATED");
        mapper.updateById(task);
        if (trigger.type() == TriggerType.IMMEDIATE && trigger.enabled()) {
            var queued = executions.queue(task.getId()); queued.setScheduledTime(null); saveSchedulingState(queued); return queued;
        }
        return task;
    }

    /** Bounded due-definition scan; active, paused and cancelled tasks are never automatically overlapped. */
    public List<InspectionTask> due(LocalDateTime now) {
        return mapper.selectList(Wrappers.<InspectionTask>lambdaQuery().isNotNull(InspectionTask::getTriggerConfigurationJson)
                .eq(InspectionTask::getEnabled, true).le(InspectionTask::getScheduledTime, now)
                .in(InspectionTask::getStatus, List.of("SCHEDULED", "SUCCEEDED", "FAILED", "PARTIAL_FAILED"))
                .orderByAsc(InspectionTask::getScheduledTime).orderByAsc(InspectionTask::getId).last("LIMIT 20"));
    }

    /** The definition lock serializes multiple pollers; each due occurrence begins a new logical run. */
    @Transactional(isolation = org.springframework.transaction.annotation.Isolation.REPEATABLE_READ)
    public InspectionTask queueDue(String id, LocalDateTime now) {
        var task = locked(id);
        if (!eligible(task, now)) return null;
        var stored = decode(task.getTriggerConfigurationJson());
        if (stored.trigger().type() != TriggerType.PERIODIC && task.getCurrentExecutionId() != null) return null;
        var currentScope = scope.revalidateExecutionScope(stored.scope());
        task.setCurrentExecutionId(null); task.setStatus("CREATED");
        task.setProcessedMessages(0); task.setFailedMessages(0); task.setPauseRequested(false); task.setCancelRequested(false);
        saveSchedulingState(task);
        return scope.withinExecutionScope(currentScope, () -> {
            var queued = executions.queue(id);
            // At most one run after a missed deadline; no concurrent catch-up backlog is generated.
            queued.setScheduledTime(stored.trigger().type() == TriggerType.PERIODIC ? stored.trigger().next(now) : null);
            saveSchedulingState(queued); return queued;
        });
    }

    /** Explicit enable refreshes the authorization bound; disabling does not interrupt a running conversation. */
    @Transactional
    public InspectionTask setEnabled(String id, boolean enabled) {
        tasks.get(id);
        var task = locked(id);
        if (task.getTriggerConfigurationJson() == null) throw IqcException.invalidState("旧任务没有统一触发配置");
        var stored = decode(task.getTriggerConfigurationJson());
        if (enabled && stored.trigger().type() != TriggerType.PERIODIC && task.getCurrentExecutionId() != null)
            throw IqcException.invalidState("一次性任务已经触发，不能再次启用");
        task.setEnabled(enabled);
        var definition = new Trigger(stored.trigger().type(), stored.trigger().scheduledAt(), stored.trigger().cron(), enabled);
        task.setTriggerConfigurationJson(encode(new StoredTrigger(definition, enabled ? scope.captureExecutionScope() : stored.scope())));
        if (enabled) {
            task.setScheduledTime(stored.trigger().next(schedulingNow()));
            if (List.of("CREATED", "CANCELLED").contains(task.getStatus())) task.setStatus("SCHEDULED");
        }
        mapper.updateById(task); return task;
    }

    /** Queue validation failures have no engine run; move to the next deadline without altering old attempts. */
    @Transactional
    public void recordDispatchFailure(String id, LocalDateTime expectedDeadline, LocalDateTime now) {
        var task = locked(id);
        if (!eligible(task, now) || !java.util.Objects.equals(task.getScheduledTime(), expectedDeadline)) return;
        var trigger = decode(task.getTriggerConfigurationJson()).trigger();
        task.setStatus("FAILED"); task.setCurrentExecutionId(null);
        task.setScheduledTime(trigger.type() == TriggerType.PERIODIC ? trigger.next(now) : null);
        saveSchedulingState(task);
    }

    /** Called by HTTP/scheduler only after the queue transaction returns successfully. */
    public void start(InspectionTask queued) {
        if (queued != null && "QUEUED".equals(queued.getStatus())) executions.executeAsync(queued.getId(), queued.getCurrentExecutionId());
    }
    private void saveSchedulingState(InspectionTask task) {
        mapper.updateById(task);
        // MyBatis omits null entity fields; these two nullable scheduling fields must be cleared explicitly.
        mapper.update(null, Wrappers.<InspectionTask>lambdaUpdate().eq(InspectionTask::getId, task.getId())
                .set(InspectionTask::getCurrentExecutionId, task.getCurrentExecutionId())
                .set(InspectionTask::getScheduledTime, task.getScheduledTime()));
    }
    private InspectionTask locked(String id) {
        var task = mapper.selectOne(Wrappers.<InspectionTask>lambdaQuery().eq(InspectionTask::getId, id).last("FOR UPDATE"));
        if (task == null) throw IqcException.notFound("质检任务不存在"); return task;
    }
    private boolean eligible(InspectionTask task, LocalDateTime now) {
        return task.getTriggerConfigurationJson() != null && Boolean.TRUE.equals(task.getEnabled())
                && task.getScheduledTime() != null && !task.getScheduledTime().isAfter(now)
                && List.of("SCHEDULED", "SUCCEEDED", "FAILED", "PARTIAL_FAILED").contains(task.getStatus());
    }
    private String encode(StoredTrigger value) {
        try { return json.writeValueAsString(value); }
        catch (com.fasterxml.jackson.core.JsonProcessingException failure) { throw new IllegalStateException("触发配置保存失败", failure); }
    }
    private StoredTrigger decode(String value) {
        try { return json.readValue(value, StoredTrigger.class); }
        catch (com.fasterxml.jackson.core.JsonProcessingException failure) { throw IqcException.invalidState("任务触发配置无效"); }
    }
}
